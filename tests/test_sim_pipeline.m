function testSaveRunManifest(testCase)
startup();

tempProjectRoot = tempname;
mkdir(tempProjectRoot);
cleanup = onCleanup(@() rmdir(tempProjectRoot, 's')); %#ok<NASGU>

cfg = load_sim_config(struct( ...
    'path', struct('projectRoot', tempProjectRoot), ...
    'output', struct('enableSave', true)));
runInfo = prepare_run_dir(cfg);

provenance = build_pipeline_provenance(struct( ...
    'mode', 'sim', ...
    'config', cfg, ...
    'runInfo', runInfo, ...
    'sourceData', struct( ...
        'track', struct('x', 1:3), ...
        'echo', zeros(4, 3), ...
        'mask', [true, false, true], ...
        'meta', struct('kind', 'sim', 'provider', 'unit')), ...
    'degradationInfo', struct('mode', 'fixed_gap', 'missingRatio', 1/3, 'totalMissing', 1), ...
    'recoveryResult', struct('status', 'skipped', 'method', 'cs_1d'), ...
    'imageResult', struct( ...
        'grid', struct('numPixels', 32, 'xLimits', [-5, 5], 'yLimits', [-5, 5]), ...
        'peak', struct('value', 10)), ...
    'analysisResult', struct('status', 'disabled'), ...
    'recoveryEvaluation', struct('enabled', false, 'status', 'disabled'), ...
    'backend', struct('name', 'cpu')));

result = struct('provenance', provenance);
filePath = save_run_manifest(result, runInfo, cfg);

verifyTrue(testCase, exist(filePath, 'file') == 2);
manifestText = fileread(filePath);
verifySubstring(testCase, manifestText, 'Run Manifest');
verifySubstring(testCase, manifestText, '[Source Data]');
verifySubstring(testCase, manifestText, '- kind: sim');
verifySubstring(testCase, manifestText, '[Degradation]');
verifySubstring(testCase, manifestText, '- mode: fixed_gap');

runInfo.enabled = false;
skippedPath = save_run_manifest(result, runInfo, cfg);
verifyEqual(testCase, skippedPath, '');
end
