function testSimPipelineSmoke(testCase)
startup();

cfg = load_sim_config(struct( ...
    'output', struct('enableSave', false), ...
    'analysis', struct('enablePointAnalysis', false), ...
    'degradation', struct('mode', 'none', 'enable', false), ...
    'scene', struct( ...
        'inheritRealTrack', false, ...
        'targetPositions', [0, 0, 0; 8, 6, 0], ...
        'targetAmplitudes', [1; 0.6], ...
        'targetPhasesDeg', [0; 20], ...
        'numAzimuthSamples', 48, ...
        'numRangeSamples', 96, ...
        'trackXLimits', [-50, 50], ...
        'trackYValue', -120, ...
        'trackZValue', 80), ...
    'radar', struct( ...
        'inheritRealRadar', false, ...
        'bandwidthHz', 2e8), ...
    'imaging', struct('grid', struct('numPixels', 64, 'xLimits', [-20, 20], 'yLimits', [-20, 20]), ...
                      'showProgress', false)));

result = run_sim_data_pipeline(cfg);

verifyEqual(testCase, size(result.image.image), [64, 64]);
verifyEqual(testCase, result.summary.targetCount, 2);
verifyEqual(testCase, result.degradation.totalMissing, 0);
verifyGreaterThan(testCase, result.image.peak.value, 0);
verifyEqual(testCase, result.source.meta.kind, 'sim');
end

function testSimPipelineWithRecovery(testCase)
startup();

cfg = load_sim_config(struct( ...
    'output', struct('enableSave', false), ...
    'analysis', struct( ...
        'enablePointAnalysis', true, ...
        'enableImageQuality', true, ...
        'pointTarget', struct( ...
            'cutoutHeight', 16, ...
            'cutoutWidth', 16, ...
            'upsampleFactor', 8)), ...
    'degradation', struct( ...
        'enable', true, ...
        'mode', 'fixed_gap', ...
        'fixedGapRanges', [12, 18]), ...
    'recovery', struct( ...
        'enable', true, ...
        'method', '1d', ...
        'maxIter', 12, ...
        'verbose', false), ...
    'scene', struct( ...
        'inheritRealTrack', false, ...
        'targetPositions', [0, 0, 0], ...
        'targetAmplitudes', 1, ...
        'targetPhasesDeg', 0, ...
        'numAzimuthSamples', 48, ...
        'numRangeSamples', 96, ...
        'trackXLimits', [-50, 50], ...
        'trackYValue', -120, ...
        'trackZValue', 80), ...
    'radar', struct( ...
        'inheritRealRadar', false, ...
        'bandwidthHz', 2e8), ...
    'imaging', struct('grid', struct('numPixels', 64, 'xLimits', [-20, 20], 'yLimits', [-20, 20]), ...
                      'showProgress', false)));

result = run_sim_data_pipeline(cfg);

verifyEqual(testCase, result.recovery.status, 'completed');
verifyEqual(testCase, result.summary.recoveryStatus, 'completed');
verifyEqual(testCase, size(result.image.image), [64, 64]);
verifyGreaterThan(testCase, result.recovery.recoveryInfo.iterations, 0);
verifyEqual(testCase, result.analysis.status, 'completed');
verifyEqual(testCase, result.analysis.pointTarget.status, 'completed');
verifyEqual(testCase, result.analysis.imageQuality.status, 'completed');
verifyGreaterThan(testCase, result.analysis.imageQuality.metrics.psnr, 0);
end

function testBuildPlatformTrackArc(testCase)
