function testSimPipelineSmoke(testCase)
startup();

cfg = load_sim_config(struct( ...
    'output', struct('enableSave', false), ...
    'analysis', struct( ...
        'enablePointAnalysis', false, ...
        'recoveryEvaluation', struct('enable', false)), ...
    'degradation', struct('mode', 'none', 'enable', false), ...
    'scene', struct( ...
        'inheritRealTrack', false, ...
        'targetPositions', [0, 0, 0; 8, 6, 0], ...
        'targetAmplitudes', [1; 0.6], ...
        'targetPhasesDeg', [0; 20], ...
        'numAzimuthSamples', 48, ...
        'numRangeSamples', 96, ...
        'trackXLimits', [-50, 50], ...
        'trackYValue', -120, ...
        'trackZValue', 80), ...
    'radar', struct( ...
        'inheritRealRadar', false, ...
        'bandwidthHz', 2e8), ...
    'imaging', struct('grid', struct('numPixels', 64, 'xLimits', [-20, 20], 'yLimits', [-20, 20]), ...
                      'showProgress', false)));

result = run_sim_data_pipeline(cfg);

verifyEqual(testCase, size(result.image.image), [64, 64]);
verifyEqual(testCase, result.summary.targetCount, 2);
verifyEqual(testCase, result.degradation.totalMissing, 0);
verifyGreaterThan(testCase, result.image.peak.value, 0);
verifyEqual(testCase, result.source.meta.kind, 'sim');
verifyEqual(testCase, result.recoveryEvaluation.status, 'disabled');
verifyEqual(testCase, result.summary.recoveryEvaluationStatus, 'disabled');
verifyTrue(testCase, isfield(result, 'provenance'));
verifyEqual(testCase, result.provenance.pipeline.mode, 'sim');
verifyEqual(testCase, result.files.manifest, '');

provenance = build_pipeline_provenance(struct( ...
    'mode', 'sim', ...
    'config', cfg, ...
    'sourceData', result.source, ...
    'degradationInfo', result.degradation, ...
    'recoveryResult', result.recovery, ...
    'imageResult', result.image, ...
    'analysisResult', result.analysis, ...
    'recoveryEvaluation', result.recoveryEvaluation, ...
    'backend', result.backend, ...
    'runInfo', result.run));
verifyEqual(testCase, provenance.pipeline.mode, 'sim');
verifyEqual(testCase, provenance.source.kind, 'sim');
verifyEqual(testCase, provenance.source.echoSize, [96, 48]);
verifyEqual(testCase, provenance.recovery.status, 'skipped');
verifyEqual(testCase, provenance.imaging.grid.numPixels, 64);
end

