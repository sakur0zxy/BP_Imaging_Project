function testBuildPlatformTrackBadRadius(testCase)
badScene = struct('track', struct( ...
    'mode', 'arc', ...
    'numSamples', 32, ...
    'centerXY', [10, 20], ...
    'radius', 0, ...
    'angleLimitsDeg', [-30, 30], ...
    'zValue', 50));

didThrow = false;
try
    build_platform_track(badScene);
catch errorInfo
    didThrow = true;
    verifySubstring(testCase, errorInfo.message, 'radius 必须大于 0');
end

verifyTrue(testCase, didThrow);
end

function testFullImageReferenceCache(testCase)
startup();

tempProjectRoot = tempname;
mkdir(tempProjectRoot);
cleanup = onCleanup(@() rmdir(tempProjectRoot, 's')); %#ok<NASGU>

cfg = load_sim_config(struct( ...
    'path', struct('projectRoot', tempProjectRoot), ...
    'output', struct('enableSave', false), ...
    'cache', struct( ...
        'enableFullImageCache', true, ...
        'fullImageNamespace', 'baseline'), ...
    'scene', struct( ...
        'inheritRealTrack', false, ...
        'targetPositions', [0, 0, 0], ...
        'targetAmplitudes', 1, ...
        'targetPhasesDeg', 0, ...
        'numAzimuthSamples', 32, ...
        'numRangeSamples', 64, ...
        'trackXLimits', [-40, 40], ...
        'trackYValue', -80, ...
        'trackZValue', 60), ...
    'radar', struct( ...
        'inheritRealRadar', false, ...
        'bandwidthHz', 1.5e8), ...
    'imaging', struct( ...
        'grid', struct('numPixels', 48, 'xLimits', [-15, 15], 'yLimits', [-15, 15]), ...
        'showProgress', false)));

sourceData = generate_point_target_data(cfg);

[imageResult1, cacheInfo1] = get_full_image_reference(sourceData, cfg);
[imageResult2, cacheInfo2] = get_full_image_reference(sourceData, cfg);

verifyFalse(testCase, cacheInfo1.cacheHit);
verifyTrue(testCase, cacheInfo2.cacheHit);
verifyEqual(testCase, cacheInfo1.key, cacheInfo2.key);
verifyEqual(testCase, imageResult1.image, imageResult2.image);
verifyTrue(testCase, exist(cacheInfo2.folderPath, 'dir') == 7);
verifyTrue(testCase, exist(cacheInfo2.filePath, 'file') == 2);
verifyTrue(testCase, exist(cacheInfo2.infoFilePath, 'file') == 2);
verifyTrue(testCase, exist(cacheInfo2.infoFilePathCn, 'file') == 2);
verifySubstring(testCase, cacheInfo2.folderName, 'sim_baseline_');

infoText = fileread(cacheInfo2.infoFilePath);
verifyNotEmpty(testCase, infoText);
verifySubstring(testCase, infoText, 'Full Image Reference Cache');
verifySubstring(testCase, infoText, 'Folder Name: sim_baseline_');
verifySubstring(testCase, infoText, 'Source Name: sim_generate_point_target_data');
verifySubstring(testCase, infoText, 'imaging.grid.numPixels = 48');

infoTextCn = fileread(cacheInfo2.infoFilePathCn);
verifyNotEmpty(testCase, infoTextCn);
verifySubstring(testCase, infoTextCn, '缓存生成时间 (Timestamp)');
verifySubstring(testCase, infoTextCn, '缓存目录 (Folder): sim_baseline_');
verifySubstring(testCase, infoTextCn, '【雷达核心参数】');
verifySubstring(testCase, infoTextCn, '【成像网格参数】');
end
