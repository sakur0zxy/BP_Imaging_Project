function testFullImageReferenceCache(testCase)
startup();

tempProjectRoot = tempname;
mkdir(tempProjectRoot);
cleanup = onCleanup(@() rmdir(tempProjectRoot, 's')); %#ok<NASGU>

cfg = load_sim_config(struct( ...
    'path', struct('projectRoot', tempProjectRoot), ...
    'output', struct('enableSave', false), ...
    'cache', struct( ...
        'enableFullImageCache', true, ...
        'fullImageNamespace', 'baseline'), ...
    'scene', struct( ...
        'inheritRealTrack', false, ...
        'targetPositions', [0, 0, 0], ...
        'targetAmplitudes', 1, ...
        'targetPhasesDeg', 0, ...
        'numAzimuthSamples', 32, ...
