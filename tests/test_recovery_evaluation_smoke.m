function testRunRecoveryEvaluationSimulation(testCase)
startup();

cfg = load_sim_config(struct( ...
    'output', struct('enableSave', false), ...
    'analysis', struct( ...
        'enablePointAnalysis', false, ...
        'enableImageQuality', false, ...
        'recoveryEvaluation', struct( ...
            'enable', true, ...
            'outputs', struct( ...
                'saveMat', false, ...
                'saveSummary', false, ...
                'savePanel', false, ...
                'showPanel', false), ...
            'metricOptions', struct( ...
                'enablePointAnalysis', false, ...
                'enableImageQuality', true, ...
                'compareMode', 'amplitude'))), ...
    'degradation', struct( ...
        'enable', true, ...
        'mode', 'fixed_gap', ...
        'fixedGapRanges', [12, 18]), ...
    'recovery', struct( ...
        'enable', false, ...
        'common', struct('maxIter', 10, 'verbose', false), ...
        'methods', struct( ...
            'cs_1d', struct('lambda', 0.02, 'useFista', true), ...
            'cs_2d', struct('lambda', 0.01, 'useFista', true))), ...
    'scene', struct( ...
        'inheritRealTrack', false, ...
        'targetPositions', [0, 0, 0], ...
        'targetAmplitudes', 1, ...
        'targetPhasesDeg', 0, ...
        'numAzimuthSamples', 40, ...
        'numRangeSamples', 80, ...
        'trackXLimits', [-40, 40], ...
        'trackYValue', -120, ...
        'trackZValue', 80), ...
    'radar', struct( ...
        'inheritRealRadar', false, ...
        'bandwidthHz', 2e8), ...
    'imaging', struct( ...
        'grid', struct('numPixels', 48, 'xLimits', [-15, 15], 'yLimits', [-15, 15]), ...
        'showProgress', false)));

sourceReference = generate_point_target_data(cfg);
[degradedSourceData, ~] = apply_degradation(sourceReference, cfg.degradation);

result = run_recovery_evaluation(cfg, struct( ...
    'sourceReference', sourceReference, ...
    'degradedSourceData', degradedSourceData));

verifyTrue(testCase, result.enabled);
verifyEqual(testCase, result.status, 'completed');
verifyTrue(testCase, isfield(result.cases, 'full'));
verifyTrue(testCase, isfield(result.cases, 'recovered_cs_2d'));
verifyTrue(testCase, isfield(result.comparisons, 'full_vs_recovered_cs_1d'));
verifyTrue(testCase, isfield(result.summary, 'bestMethodIfAny'));
verifyNotEmpty(testCase, result.summary.bestMethodIfAny);
verifyGreaterThan(testCase, ...
    result.comparisons.full_vs_recovered_cs_1d.metrics.metricValues.normalizedCorrelation, 0);
end

function testRunRecoveryEvaluationReal(testCase)
startup();

rootDir = tempname;
mkdir(rootDir);
dataDir = fullfile(rootDir, 'real_data');
mkdir(dataDir);
cleanup = onCleanup(@() rmdir(rootDir, 's')); %#ok<NASGU>

data = struct();
data.x = 0:23;
data.y = zeros(1, 24);
data.z = 10 * ones(1, 24);
data.fp = complex(ones(12, 24));
data.freq = linspace(9.5e9, 9.6e9, 12);
save(fullfile(dataDir, 'data_3dsar_pass1_az001_VV.mat'), 'data');

cfg = load_real_config(struct( ...
    'path', struct('projectRoot', rootDir, 'realDataRoot', dataDir), ...
    'source', struct('numFiles', 1), ...
    'output', struct('enableSave', false), ...
    'analysis', struct( ...
        'enablePointAnalysis', false, ...
        'enableImageQuality', false, ...
        'pointTarget', struct( ...
            'cutoutHeight', 16, ...
            'cutoutWidth', 16, ...
            'upsampleFactor', 8), ...
        'recoveryEvaluation', struct( ...
            'enable', true, ...
            'outputs', struct( ...
                'saveMat', false, ...
                'saveSummary', false, ...
                'savePanel', false, ...
                'showPanel', false), ...
            'metricOptions', struct( ...
                'enablePointAnalysis', true, ...
                'enableImageQuality', false, ...
                'compareMode', 'amplitude'))), ...
    'degradation', struct( ...
        'enable', true, ...
        'mode', 'fixed_gap', ...
        'fixedGapRanges', [5, 8]), ...
    'recovery', struct( ...
        'enable', false, ...
        'common', struct('maxIter', 8, 'verbose', false), ...
        'methods', struct( ...
            'cs_1d', struct('lambda', 0.02, 'useFista', true), ...
            'cs_2d', struct('lambda', 0.01, 'useFista', true))), ...
    'imaging', struct( ...
        'grid', struct('numPixels', 32, 'xLimits', [-5, 5], 'yLimits', [-5, 5]), ...
        'showProgress', false)));

sourceReference = load_gotcha_data(cfg);
[degradedSourceData, ~] = apply_degradation(sourceReference, cfg.degradation);
[fullImageResult, ~] = get_full_image_reference(sourceReference, cfg);

result = run_recovery_evaluation(cfg, struct( ...
    'sourceReference', sourceReference, ...
    'degradedSourceData', degradedSourceData, ...
    'fullImageResult', fullImageResult));

verifyTrue(testCase, result.enabled);
verifyEqual(testCase, result.status, 'completed');
verifyTrue(testCase, isfield(result.cases, 'interrupted'));
verifyTrue(testCase, isfield(result.comparisons, 'interrupted_vs_recovered_cs_1d'));
verifyTrue(testCase, isfield(result.summary, 'perCaseFindings'));
verifyTrue(testCase, ...
    result.comparisons.interrupted_vs_recovered_cs_1d.metrics.metricValues.improvementVotes >= 0);
end
