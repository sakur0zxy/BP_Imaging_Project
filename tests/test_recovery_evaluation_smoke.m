recoveryEvaluation.summary = struct( ...
    'bestMethodIfAny', 'cs_1d', ...
    'highLevelFindings', {{'test'}}, ...
    'riskOrLimitations', {{}});
recoveryEvaluation.cases = struct();

runInfo = struct( ...
    'enabled', true, ...
    'imagesDir', imagesDir, ...
    'matsDir', matsDir, ...
    'logsDir', logsDir);

files = emit_recovery_evaluation_outputs(recoveryEvaluation, runInfo, struct(), evalConfig);

