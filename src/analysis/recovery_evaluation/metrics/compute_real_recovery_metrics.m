function metricStruct = compute_real_recovery_metrics(referenceCaseResult, targetCaseResult, comparisonSpec, ~)
%COMPUTE_REAL_RECOVERY_METRICS 计算实测口径相对指标。
referencePoint = localGetPointMetrics(referenceCaseResult);
targetPoint = localGetPointMetrics(targetCaseResult);

if ~localIsPointMetricsAvailable(referencePoint) || ~localIsPointMetricsAvailable(targetPoint)
    metricStruct = localSkippedMetrics('missing-point-target-metrics');
    return;
end

deltaPslrDb = targetPoint.avgPslrDb - referencePoint.avgPslrDb;
deltaIslrDb = targetPoint.avgIslrDb - referencePoint.avgIslrDb;
deltaIrwPhysical = targetPoint.avgIrwPhysical - referencePoint.avgIrwPhysical;
peakShiftPixels = hypot(targetPoint.peakRow - referencePoint.peakRow, ...
    targetPoint.peakCol - referencePoint.peakCol);
closenessScore = abs(deltaPslrDb) + abs(deltaIslrDb) + abs(deltaIrwPhysical) + peakShiftPixels;

improvementVotes = NaN;
if strcmp(comparisonSpec.referenceCase, 'interrupted')
    improvementVotes = double(deltaPslrDb > 0) ...
        + double(deltaIslrDb < 0) ...
        + double(deltaIrwPhysical < 0);
end

metricStruct = struct();
metricStruct.metricNames = {'deltaPslrDb', 'deltaIslrDb', 'deltaIrwPhysical', 'peakShiftPixels', 'closenessScore', 'improvementVotes'};
metricStruct.metricValues = struct( ...
    'deltaPslrDb', deltaPslrDb, ...
    'deltaIslrDb', deltaIslrDb, ...
    'deltaIrwPhysical', deltaIrwPhysical, ...
    'peakShiftPixels', peakShiftPixels, ...
    'closenessScore', closenessScore, ...
    'improvementVotes', improvementVotes);
metricStruct.metricInterpretation = struct( ...
    'deltaPslrDb', '相对 interrupted 时越大越好；相对 full 时越接近 0 越好', ...
    'deltaIslrDb', '相对 interrupted 时越小越好；相对 full 时越接近 0 越好', ...
    'deltaIrwPhysical', '相对 interrupted 时越小越好；相对 full 时越接近 0 越好', ...
    'peakShiftPixels', '越小越好', ...
    'closenessScore', '越小越接近参考 case', ...
    'improvementVotes', '相对 interrupted 时越大越好');
metricStruct.validity = true;
metricStruct.status = 'completed';
metricStruct.meta = struct( ...
    'comparisonName', comparisonSpec.comparisonName, ...
    'referenceCase', referenceCaseResult.caseName, ...
    'targetCase', targetCaseResult.caseName, ...
    'mode', 'real');
end

function pointMetrics = localGetPointMetrics(caseResult)
pointMetrics = struct();
if isfield(caseResult, 'metrics') && isstruct(caseResult.metrics) ...
        && isfield(caseResult.metrics, 'pointTarget')
    pointMetrics = caseResult.metrics.pointTarget;
end
end

function tf = localIsPointMetricsAvailable(pointMetrics)
tf = isstruct(pointMetrics) ...
    && isfield(pointMetrics, 'available') ...
    && logical(pointMetrics.available);
end

function metricStruct = localSkippedMetrics(reason)
metricStruct = struct();
metricStruct.metricNames = {};
metricStruct.metricValues = struct();
metricStruct.metricInterpretation = struct();
metricStruct.validity = false;
metricStruct.status = 'skipped';
metricStruct.meta = struct('reason', reason, 'mode', 'real');
end
