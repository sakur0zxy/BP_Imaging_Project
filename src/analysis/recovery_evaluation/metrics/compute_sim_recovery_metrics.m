function metricStruct = compute_sim_recovery_metrics(referenceCaseResult, targetCaseResult, comparisonSpec, evalConfig)
%COMPUTE_SIM_RECOVERY_METRICS 计算仿真口径绝对指标。
referenceImage = localGetCaseImage(referenceCaseResult);
targetImage = localGetCaseImage(targetCaseResult);

if isempty(referenceImage) || isempty(targetImage)
    metricStruct = localSkippedMetrics('missing-image-result');
    return;
end

options = struct('compareMode', evalConfig.metricOptions.compareMode);
imageQuality = evaluate_image_quality(referenceImage, targetImage, options);

metricStruct = struct();
metricStruct.metricNames = {'psnr', 'relativeL2Error', 'normalizedCorrelation', 'rmse', 'mae'};
metricStruct.metricValues = struct( ...
    'psnr', imageQuality.psnr, ...
    'relativeL2Error', imageQuality.relativeL2Error, ...
    'normalizedCorrelation', imageQuality.normalizedCorrelation, ...
    'rmse', imageQuality.rmse, ...
    'mae', imageQuality.mae);
metricStruct.metricInterpretation = struct( ...
    'psnr', '越大越好', ...
    'relativeL2Error', '越小越好', ...
    'normalizedCorrelation', '越大越好', ...
    'rmse', '越小越好', ...
    'mae', '越小越好');
metricStruct.validity = true;
metricStruct.status = 'completed';
metricStruct.meta = struct( ...
    'comparisonName', comparisonSpec.comparisonName, ...
    'referenceCase', referenceCaseResult.caseName, ...
    'targetCase', targetCaseResult.caseName, ...
    'mode', 'simulation');
end

function imageData = localGetCaseImage(caseResult)
imageData = [];
if isfield(caseResult, 'artifacts') && isstruct(caseResult.artifacts) ...
        && isfield(caseResult.artifacts, 'imageResult') ...
        && isstruct(caseResult.artifacts.imageResult) ...
        && isfield(caseResult.artifacts.imageResult, 'image')
    imageData = caseResult.artifacts.imageResult.image;
end
end

function metricStruct = localSkippedMetrics(reason)
metricStruct = struct();
metricStruct.metricNames = {};
metricStruct.metricValues = struct();
metricStruct.metricInterpretation = struct();
metricStruct.validity = false;
metricStruct.status = 'skipped';
metricStruct.meta = struct('reason', reason, 'mode', 'simulation');
end
