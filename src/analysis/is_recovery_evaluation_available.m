function [isAvailable, missingFunctions] = is_recovery_evaluation_available()
%IS_RECOVERY_EVALUATION_AVAILABLE 检查恢复评估子模块是否完整可用。

requiredFunctions = { ...
    'run_recovery_evaluation', ...
    'prepare_recovery_evaluation_config', ...
    'build_recovery_evaluation_cases', ...
    'evaluate_recovery_cases', ...
    'summarize_recovery_evaluation', ...
    'compute_sim_recovery_metrics', ...
    'compute_real_recovery_metrics', ...
    'build_case_result', ...
    'build_comparison_result', ...
    'emit_recovery_evaluation_outputs', ...
    'plot_recovery_evaluation_panel', ...
    'plot_recovery_evaluation_point_target_panel'};

missingFunctions = {};
for idx = 1:numel(requiredFunctions)
    functionName = requiredFunctions{idx};
    if exist(functionName, 'file') ~= 2
        missingFunctions{end + 1} = functionName; %#ok<AGROW>
    end
end

isAvailable = isempty(missingFunctions);
end
